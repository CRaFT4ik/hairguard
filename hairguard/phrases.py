# ---------------------------------------------------------------------------
# State management
# ---------------------------------------------------------------------------

_DEFAULT_STATE_PATH = Path.home() / ".hairguard" / "phrase_state.json"


class PhraseManager:
    """Returns phrases in a persistent shuffled order.

    All phrases are shown before any repeats.  State survives restarts.
    Thread-safe via a Lock.
    """

    def __init__(self, state_path: Path | str | None = None) -> None:
        self._path = Path(state_path) if state_path else _DEFAULT_STATE_PATH
        self._lock = threading.Lock()
        self._indices: list[int] = []
        self._current_index: int = 0
        self._load()

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _new_shuffle(self) -> None:
        """Create a fresh random shuffle of all phrase indices."""
        indices = list(range(len(PHRASES)))
        random.shuffle(indices)
        self._indices = indices
        self._current_index = 0

    def _load(self) -> None:
        """Load state from disk; create a new shuffle if state is absent/invalid."""
        try:
            with open(self._path, "r", encoding="utf-8") as fh:
                state = json.load(fh)
            indices = state["shuffled_indices"]
            current = state["current_index"]
            # Validate: indices must be a permutation of range(len(PHRASES))
            if (
                isinstance(indices, list)
                and isinstance(current, int)
                and sorted(indices) == list(range(len(PHRASES)))
                and 0 <= current <= len(indices)
            ):
                self._indices = indices
                self._current_index = current
                return
        except (FileNotFoundError, KeyError, TypeError, ValueError, json.JSONDecodeError):
            pass

        self._new_shuffle()
        self._save()

    def _save(self) -> None:
        """Persist current state to disk."""
        self._path.parent.mkdir(parents=True, exist_ok=True)
        state = {
            "shuffled_indices": self._indices,
            "current_index": self._current_index,
        }
        # Write atomically via a temp file
        tmp = self._path.with_suffix(".json.tmp")
        with open(tmp, "w", encoding="utf-8") as fh:
            json.dump(state, fh)
        tmp.replace(self._path)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def get_next_phrase(self) -> str:
        """Return the next phrase in the shuffled sequence.

        When all phrases have been shown, the list is reshuffled and the
        cycle restarts from the beginning.
        """
        with self._lock:
            if self._current_index >= len(self._indices):
                self._new_shuffle()

            phrase = PHRASES[self._indices[self._current_index]]
            self._current_index += 1
            self._save()
            return phrase
